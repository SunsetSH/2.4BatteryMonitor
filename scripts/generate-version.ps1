param([string]$Version = '0.0.0')
$ErrorActionPreference = 'Stop'
if ($Version -notmatch '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)$') {
    throw 'Version must be MAJOR.MINOR.PATCH without a prefix or suffix.'
}
$parts = $Version.Split('.')
foreach ($part in $parts) {
    if ($part.Length -gt 5 -or [int]$part -gt 65535) { throw 'Version components must fit a Windows version resource (0..65535).' }
}
$root = Split-Path $PSScriptRoot -Parent
$repo = (Get-Content -Raw -LiteralPath (Join-Path $root 'installer\update-repository.txt')).Trim()
if ($repo -cnotmatch '^[A-Za-z0-9-]{1,39}/[A-Za-z0-9_][A-Za-z0-9_.-]{0,99}$') {
    throw 'Expected OWNER/REPO in installer/update-repository.txt.'
}
$keyPath = Join-Path $root 'installer\update-public-key.txt'
$publicKey = ''
if (Test-Path -LiteralPath $keyPath) {
    $publicKey = (Get-Content -Raw -LiteralPath $keyPath).Trim()
    if ($publicKey -cnotmatch '^4543533120000000[0-9A-Fa-f]{128}$') {
        throw 'Expected a CNG ECDSA P-256 public blob in installer/update-public-key.txt.'
    }
}
$build = Join-Path $root 'build'
New-Item -ItemType Directory -Force $build | Out-Null
$path = Join-Path $build 'version.h'
$content = @"
// Generated by scripts/generate-version.ps1. Do not edit.
#pragma once
#define WB_VERSION_MAJOR $($parts[0])
#define WB_VERSION_MINOR $($parts[1])
#define WB_VERSION_PATCH $($parts[2])
#define WB_VERSION_RESOURCE $($parts -join ','),0
#define WB_VERSION_STRING "$Version"
#define WB_UPDATE_REPO "$repo"
#define WB_UPDATE_REPO_W L"$repo"
#define WB_UPDATE_PUBLIC_KEY "$publicKey"
"@
if (-not (Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -ne $content) {
    [IO.File]::WriteAllText($path, $content, [Text.UTF8Encoding]::new($false))
}
